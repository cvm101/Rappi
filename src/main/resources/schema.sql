-- Portable between Supabase (Postgres) and H2. Re-applied on every startup => demo reset.
DROP TABLE IF EXISTS agent_decision;
DROP TABLE IF EXISTS purchase_order;
DROP TABLE IF EXISTS supplier_product;
DROP TABLE IF EXISTS supplier;
DROP TABLE IF EXISTS storage_capacity;
DROP TABLE IF EXISTS budget;
DROP TABLE IF EXISTS demand_forecast;
DROP TABLE IF EXISTS inventory;
DROP TABLE IF EXISTS product;

CREATE TABLE product (
    id          BIGINT PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    unit_volume DOUBLE PRECISION NOT NULL,
    unit_cost   DOUBLE PRECISION NOT NULL
);

CREATE TABLE inventory (
    id         BIGINT PRIMARY KEY,
    product_id BIGINT NOT NULL,
    node_id    VARCHAR(20) NOT NULL,
    on_hand    INT NOT NULL
);

CREATE TABLE demand_forecast (
    id           BIGINT PRIMARY KEY,
    product_id   BIGINT NOT NULL,
    node_id      VARCHAR(20) NOT NULL,
    daily_demand DOUBLE PRECISION NOT NULL
);

CREATE TABLE budget (
    id               BIGINT PRIMARY KEY,
    node_id          VARCHAR(20) NOT NULL,
    remaining_amount DOUBLE PRECISION NOT NULL
);

CREATE TABLE storage_capacity (
    id              BIGINT PRIMARY KEY,
    node_id         VARCHAR(20) NOT NULL,
    capacity_volume DOUBLE PRECISION NOT NULL,
    used_volume     DOUBLE PRECISION NOT NULL
);

CREATE TABLE supplier (
    id                BIGINT PRIMARY KEY,
    name              VARCHAR(100) NOT NULL,
    lead_time_days    INT NOT NULL,
    moq               INT NOT NULL,
    reliability_score DOUBLE PRECISION NOT NULL
);

CREATE TABLE supplier_product (
    id            BIGINT PRIMARY KEY,
    supplier_id   BIGINT NOT NULL,
    product_id    BIGINT NOT NULL,
    unit_price    DOUBLE PRECISION NOT NULL,
    available_qty INT NOT NULL
);

CREATE TABLE purchase_order (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  BIGINT NOT NULL,
    supplier_id BIGINT NOT NULL,
    node_id     VARCHAR(20) NOT NULL,
    quantity    INT NOT NULL,
    unit_price  DOUBLE PRECISION NOT NULL,
    status      VARCHAR(20) NOT NULL,
    source      VARCHAR(20) NOT NULL,
    note        VARCHAR(500),
    created_at  TIMESTAMP NOT NULL
);

CREATE TABLE agent_decision (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scenario        VARCHAR(30) NOT NULL,
    product_id      BIGINT,
    node_id         VARCHAR(20),
    decision        VARCHAR(20),
    reasoning       TEXT,
    final_status    VARCHAR(30),
    attempts        INT NOT NULL,
    po_ids          VARCHAR(200),
    trace_json      TEXT,
    validation_json TEXT,
    created_at      TIMESTAMP NOT NULL
);
